#!/usr/bin/env python3
"""Build plugins/seo-kit/knowledge/INDEX.md from the audit-check tables.

Scans knowledge/*.md (top level only; adapters/ and the exempt files are skipped),
finds every `## Audit checks` and `## Procedures` section, and parses the rows of
tables whose header is exactly `| ID | Check | How to verify | Severity | Source |`.

Usage:
  python tools/build_index.py              # write INDEX.md
  python tools/build_index.py --check      # exit 1 + unified diff if INDEX.md is stale
  python tools/build_index.py --root PATH  # repo root (default: parent of tools/)

Standard library only, Python 3.9+. This module also holds the small parsing helpers
shared with check_knowledge.py.
"""
import argparse
import datetime
import difflib
import re
import sys
from pathlib import Path

KNOWLEDGE_REL = Path("plugins") / "seo-kit" / "knowledge"
EXCLUDED_FILES = {"INDEX.md", "conventions.md", "archetypes.md", "myths-deprecated.md"}
SECTION_NAMES = ("audit checks", "procedures")
CHECK_HEADER = ["ID", "Check", "How to verify", "Severity", "Source"]
ID_RE = re.compile(r"^[A-Z]{2}-\d{2,}$")
ALIAS_RE = re.compile(r"^\W*Alias of ([A-Z]{2}-\d+)")
MAX_CHECK_LEN = 120
DATE_LINE_RE = re.compile(r"^> Generated by tools/build_index\.py on \d{4}-\d{2}-\d{2} ")


# --------------------------------------------------------------------------- helpers

def default_root():
    return Path(__file__).resolve().parent.parent


def read_text(path):
    return Path(path).read_text(encoding="utf-8-sig")


def split_row(line):
    """Split a markdown table row into stripped cells.

    Honours backslash-escaped pipes and pipes inside backtick code spans.
    Returns None when the line is not a table row.
    """
    s = line.strip()
    if not s.startswith("|"):
        return None
    cells, buf = [], []
    in_code = False
    i = 1
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s) and s[i + 1] == "|":
            buf.append("|")
            i += 2
            continue
        if ch == "`":
            in_code = not in_code
        if ch == "|" and not in_code:
            cells.append("".join(buf).strip())
            buf = []
        else:
            buf.append(ch)
        i += 1
    tail = "".join(buf).strip()
    if tail:  # row without trailing pipe
        cells.append(tail)
    return cells


def is_separator(cells):
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", c.replace(" ", "")) for c in cells)


def iter_lines(text):
    """Yield (lineno, line, in_fence); fence marker lines count as in_fence."""
    in_fence = False
    marker = ""
    for n, line in enumerate(text.splitlines(), 1):
        stripped = line.lstrip()
        m = re.match(r"(`{3,}|~{3,})", stripped)
        if m:
            if not in_fence:
                in_fence, marker = True, m.group(1)[0]
                yield n, line, True
                continue
            if m.group(1)[0] == marker:
                in_fence = False
                yield n, line, True
                continue
        yield n, line, in_fence


def github_slug(heading):
    s = heading.strip().lower()
    s = re.sub(r"[^\w\- ]", "", s)
    return s.replace(" ", "-")


def parse_headings(text):
    """Return list of (lineno, level, title) outside fenced code."""
    out = []
    for n, line, in_fence in iter_lines(text):
        if in_fence:
            continue
        m = re.match(r"^(#{1,6})\s+(.*?)\s*#*\s*$", line)
        if m:
            out.append((n, len(m.group(1)), m.group(2)))
    return out


def parse_prefix_table(conventions_path):
    """Parse the Check-IDs prefix table of conventions.md.

    Returns an ordered list of (prefix, filename). The table is laid out as two
    side-by-side column pairs; the order is the left pair top to bottom, then the
    right pair top to bottom.
    """
    text = read_text(conventions_path)
    lines = text.splitlines()
    left, right = [], []
    i = 0
    while i < len(lines):
        cells = split_row(lines[i])
        if cells and [c.lower() for c in cells[:2]] == ["prefix", "file"]:
            i += 1
            while i < len(lines):
                row = split_row(lines[i])
                if row is None:
                    break
                if not is_separator(row):
                    row = (row + ["", "", "", ""])[:4]
                    row = [c.strip("` ") for c in row]
                    if row[0] and row[1]:
                        left.append((row[0], row[1]))
                    if row[2] and row[3]:
                        right.append((row[2], row[3]))
                i += 1
            break
        i += 1
    return left + right


def knowledge_dir(root):
    return Path(root) / KNOWLEDGE_REL


# --------------------------------------------------------------------------- parsing

def extract_checks(path):
    """Yield dicts for every check row under Audit checks / Procedures sections."""
    text = read_text(path)
    headings = parse_headings(text)
    # slugs, GitHub style: duplicates get -1, -2 ...
    seen = {}
    slug_at = {}
    for n, _lvl, title in headings:
        base = github_slug(title)
        k = seen.get(base, 0)
        slug_at[n] = base if k == 0 else "%s-%d" % (base, k)
        seen[base] = k + 1

    section_slug = None
    in_table = False
    header_ok = False
    rows = []
    h_by_line = {n: (lvl, title) for n, lvl, title in headings}
    for n, line, in_fence in iter_lines(text):
        if in_fence:
            in_table = False
            continue
        if n in h_by_line:
            lvl, title = h_by_line[n]
            if lvl <= 2:
                section_slug = slug_at[n] if (lvl == 2 and title.strip().lower() in SECTION_NAMES) else None
            in_table = False
            continue
        if section_slug is None:
            continue
        cells = split_row(line)
        if cells is None:
            in_table = False
            continue
        if not in_table:
            in_table = True
            header_ok = cells == CHECK_HEADER
            continue
        if is_separator(cells) or not header_ok:
            continue
        if len(cells) != len(CHECK_HEADER):
            continue
        rows.append({
            "id": cells[0], "check": cells[1], "severity": cells[3],
            "file": Path(path).name, "slug": section_slug, "line": n,
        })
    return rows


def truncate(text, limit=MAX_CHECK_LEN):
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) <= limit:
        return text
    cut = text[: limit - 1]
    if text[limit - 1] != " " and " " in cut:  # cut mid-word: back up to the last space
        cut = cut[: cut.rfind(" ")]
    cut = cut.rstrip(" ,;:.-—")
    if cut.count("`") % 2:  # do not leave an unbalanced code span
        cut = cut[: cut.rfind("`")].rstrip(" ,;:.-—")
    return cut + "…"


def sort_key(prefix_order):
    def key(row):
        m = re.match(r"^([A-Z]+)-(\d+)$", row["id"])
        if not m:
            return (len(prefix_order) + 1, row["id"], 0)
        pre, num = m.group(1), int(m.group(2))
        return (prefix_order.get(pre, len(prefix_order)), pre, num)
    return key


def collect(root):
    kdir = knowledge_dir(root)
    conv = kdir / "conventions.md"
    if not conv.is_file():
        raise SystemExit("error: %s not found" % conv)
    prefixes = parse_prefix_table(conv)
    if not prefixes:
        raise SystemExit("error: no prefix table found in %s" % conv)
    order = {p: i for i, (p, _f) in enumerate(prefixes)}
    files = sorted(p for p in kdir.glob("*.md") if p.name not in EXCLUDED_FILES)
    rows, contributing = [], set()
    for f in files:
        for r in extract_checks(f):
            if not ID_RE.match(r["id"]):
                sys.stderr.write("warning: %s:%d: skipped row with malformed ID %r\n" % (f.name, r["line"], r["id"]))
                continue
            rows.append(r)
            contributing.add(f.name)
    rows.sort(key=sort_key(order))
    return rows, len(contributing)


def render(rows, n_files, date_str):
    n_alias = 0
    body = []
    for r in rows:
        m = ALIAS_RE.match(r["check"])
        alias = ""
        if m:
            alias = "alias→" + m.group(1)
            n_alias += 1
        check = truncate(r["check"]).replace("|", "\\|")
        body.append("| %s | %s | %s | %s#%s | %s |" % (r["id"], r["severity"], check, r["file"], r["slug"], alias))
    out = [
        "# Knowledge index (generated — do not edit by hand)",
        "> Generated by tools/build_index.py on %s from %d files, %d checks (%d aliases)." % (date_str, n_files, len(rows), n_alias),
        "",
        "| ID | Severity | Check | Where | Alias of |",
        "|---|---|---|---|---|",
    ] + body
    return "\n".join(out) + "\n"


def strip_date(text):
    return "\n".join("> Generated by tools/build_index.py on <date> " + l[len(m.group(0)):] if (m := DATE_LINE_RE.match(l)) else l
                     for l in text.splitlines()) + "\n"


# --------------------------------------------------------------------------- main

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=None, help="repo root (default: parent of tools/)")
    ap.add_argument("--check", action="store_true", help="exit 1 and print a diff if INDEX.md is stale")
    ap.add_argument("--date", default=None, help="date to stamp, YYYY-MM-DD (default: today)")
    args = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")

    root = Path(args.root) if args.root else default_root()
    rows, n_files = collect(root)
    date_str = args.date or datetime.date.today().isoformat()
    new_text = render(rows, n_files, date_str)
    index_path = knowledge_dir(root) / "INDEX.md"

    if args.check:
        if not index_path.is_file():
            print("INDEX.md is missing: run tools/build_index.py")
            return 1
        current = read_text(index_path).replace("\r\n", "\n")
        a, b = strip_date(current), strip_date(new_text)
        if a == b:
            print("INDEX.md is up to date (%d checks)." % len(rows))
            return 0
        diff = difflib.unified_diff(a.splitlines(), b.splitlines(), "INDEX.md (current)", "INDEX.md (generated)", lineterm="")
        print("\n".join(diff))
        print("INDEX.md is stale: run tools/build_index.py")
        return 1

    index_path.parent.mkdir(parents=True, exist_ok=True)
    with open(index_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(new_text)
    print("Wrote %s (%d checks from %d files)." % (index_path, len(rows), n_files))
    return 0


if __name__ == "__main__":
    sys.exit(main())

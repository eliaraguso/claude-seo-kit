class RuleTests(TreeCase):
    def crawl(self, **kw):
        return self.write(self.k / "crawling-indexing.md", topic(**kw))

    def assertFires(self, rule, **lint_kw):
        code, rules = self.rules("--only", rule, **lint_kw)
        self.assertIn(rule, rules, "%s did not fire" % rule)
        self.assertEqual(code, 0 if rule in ck.WARNING_RULES else 1)

    def assertSilent(self, rule, **lint_kw):
        code, rules = self.rules("--only", rule, **lint_kw)
        self.assertEqual(rules, [], "%s fired unexpectedly" % rule)
        self.assertEqual(code, 0)


class BuildIndexTests(TreeCase):
    def test_generates_sorted_index_with_alias_and_anchor(self):
        self.write(self.k / "rendering-javascript.md", topic("Rendering", row("RJ-02", "Second") + row("RJ-01", "First", sev="Critical")))
        self.write(self.k / "crawling-indexing.md", topic("Crawling", row("CI-10", "Ten") + row("CI-02", "Alias of RJ-01 — verify there, report once", sev="Critical")))
        self.write(self.k / "ai-search.md", topic("AI", row("AI-01", "AI check", sev="Low")))
        code, _ = self.index()
        self.assertEqual(code, 0)
        text = (self.k / "INDEX.md").read_text(encoding="utf-8")
        self.assertTrue(text.startswith("# Knowledge index (generated — do not edit by hand)\n"))
        self.assertIn("> Generated by tools/build_index.py on 2026-10-11 from 3 files, 5 checks (1 aliases).", text)
        self.assertIn("| ID | Severity | Check | Where | Alias of |", text)
        ids = [l.split("|")[1].strip() for l in text.splitlines() if l.startswith("| ") and "ID" not in l.split("|")[1]]
        # prefix-table order is left column (CI, RJ, OP) then right (AI, ME): CI < RJ < AI
        self.assertEqual(ids, ["CI-02", "CI-10", "RJ-01", "RJ-02", "AI-01"])
        self.assertIn("| CI-02 | Critical | Alias of RJ-01 — verify there, report once | crawling-indexing.md#audit-checks | alias→RJ-01 |", text)
        self.assertIn("| RJ-01 | Critical | First | rendering-javascript.md#audit-checks |  |", text)

    def test_lf_utf8_trailing_newline_and_idempotent(self):
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01", "Café check")))
        self.index()
        raw1 = (self.k / "INDEX.md").read_bytes()
        self.assertNotIn(b"\r", raw1)
        self.assertTrue(raw1.endswith(b"\n") and not raw1.endswith(b"\n\n"))
        self.assertIn("Café".encode("utf-8"), raw1)
        self.index()
        self.assertEqual(raw1, (self.k / "INDEX.md").read_bytes())

    def test_excluded_files_and_adapters_ignored(self):
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01")))
        for name in ("archetypes.md", "myths-deprecated.md"):
            self.write(self.k / name, topic(rows=row("CI-77", "should not appear")))
        self.write(self.k / "adapters" / "astro.md", topic(rows=row("CI-78", "adapter row")))
        self.index()
        text = (self.k / "INDEX.md").read_text(encoding="utf-8")
        self.assertNotIn("CI-77", text)
        self.assertNotIn("CI-78", text)
        self.assertIn("from 1 files, 1 checks (0 aliases)", text)

    def test_procedures_section_and_wrong_header_and_fences(self):
        procs = HEADER + row("ME-01", "Procedure row")
        bad = "| ID | Controllo | Come | Gravità | Fonte |\n|---|---|---|---|---|\n| ME-09 | old | x | Alta | y |\n"
        fenced = "```\n## Audit checks\n" + HEADER + row("ME-50", "inside fence") + "```\n"
        self.write(self.k / "measurement.md", topic("Measurement", row("ME-02", "Audit row"), extra="\n## Procedures\n" + procs + "\n## Other\n" + bad + fenced))
        self.index()
        text = (self.k / "INDEX.md").read_text(encoding="utf-8")
        self.assertIn("| ME-01 | High | Procedure row | measurement.md#procedures |", text)
        self.assertIn("measurement.md#audit-checks", text)
        self.assertNotIn("ME-09", text)
        self.assertNotIn("ME-50", text)

    def test_truncation_at_word_boundary(self):
        long = " ".join(["word%02d" % i for i in range(40)])
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01", long)))
        self.index()
        line = [l for l in (self.k / "INDEX.md").read_text(encoding="utf-8").splitlines() if l.startswith("| CI-01")][0]
        cell = line.split("|")[3].strip()
        self.assertTrue(cell.endswith("…"))
        self.assertLessEqual(len(cell), 120)
        self.assertTrue(long.startswith(cell[:-1]))
        self.assertRegex(cell[:-1], r"word\d\d$")  # no half word
        short = bi.truncate("short text")
        self.assertEqual(short, "short text")

    def test_pipe_in_check_is_escaped(self):
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01", "Use `a|b` here")))
        self.index()
        text = (self.k / "INDEX.md").read_text(encoding="utf-8")
        self.assertIn("Use `a\\|b` here", text)

    def test_check_mode_clean_drift_and_date_ignored(self):
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01")))
        self.index()
        code, out = self.index("--check")
        self.assertEqual(code, 0)
        # different date only: still clean
        idx = self.k / "INDEX.md"
        idx.write_text(idx.read_text(encoding="utf-8").replace("2026-10-11", "2020-01-01"), encoding="utf-8", newline="\n")
        code, _ = self.index("--check")
        self.assertEqual(code, 0)
        # a new check makes the index stale
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01") + row("CI-02", "New check")))
        code, out = self.index("--check")
        self.assertEqual(code, 1)
        self.assertIn("+| CI-02 | High | New check", out)
        self.assertIn("--- INDEX.md (current)", out)
        # hand edit is drift too
        self.index()
        idx.write_text(idx.read_text(encoding="utf-8").replace("| High |", "| Low |"), encoding="utf-8", newline="\n")
        self.assertEqual(self.index("--check")[0], 1)

    def test_check_mode_missing_index(self):
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01")))
        code, out = self.index("--check")
        self.assertEqual(code, 1)
        self.assertIn("missing", out)

    def test_cli_exit_code(self):
        self.write(self.k / "crawling-indexing.md", topic(rows=row("CI-01")))
        script = str(REPO / "tools" / "build_index.py")
        r = subprocess.run([sys.executable, script, "--root", str(self.root)], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)
        r = subprocess.run([sys.executable, script, "--root", str(self.root), "--check"], capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_slug_helper(self):
        self.assertEqual(bi.github_slug("Audit checks"), "audit-checks")
        self.assertEqual(bi.github_slug("Facts and rules (Google)"), "facts-and-rules-google")

    def test_prefix_table_order(self):
        got = bi.parse_prefix_table(self.k / "conventions.md")
        self.assertEqual([p for p, _ in got], ["CI", "RJ", "OP", "AI", "ME"])


